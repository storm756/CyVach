def main():
    run = new_run("make_paper_pack", {})
    if PACK.exists():
        shutil.rmtree(PACK)
    for sub in ("tables", "figures", "docs", "reports"):
        (PACK / sub).mkdir(parents=True)
    shutil.copy(ROOT / "results" / "paper_numbers.md", PACK)
    for f in (ROOT / "results" / "tables").glob("*.tex"):
        shutil.copy(f, PACK / "tables")
    for f in (ROOT / "figures").glob("*.pdf"):
        shutil.copy(f, PACK / "figures")
    for d in DOCS:
        shutil.copy(ROOT / "docs" / f"{d}.md", PACK / "docs")
    for f in (ROOT / "reports").glob("*.md"):
        txt = f.read_text(encoding="utf-8")
        for pat, rep in REDACT.get(f.name, []):
            txt, n = pat.subn(rep, txt)
            assert n == 1, f"redaction pattern not found in {f.name}"
        (PACK / "reports" / f.name).write_text(txt, encoding="utf-8")
    for f in ("README_repro.md", "requirements.txt"):
        shutil.copy(ROOT / f, PACK)
    shutil.copy(ROOT / "models" / "model_card.md", PACK)
    fx = facts()
    assert fx.count("\n") <= 250, "PAPER_FACTS.md longer than 250 lines"
    (PACK / "PAPER_FACTS.md").write_text(fx, encoding="utf-8")
    # leak check against every real message
    pool = pd.read_csv(ROOT / "data" / "pool.csv", keep_default_na=False)
    real = pool[pool["is_synthetic"].astype(str) != "True"]["text"]
    keys = {normalize(t)[:40] for t in real if len(normalize(t)) >= 25}
    hits = []
    for f in PACK.rglob("*"):
        if f.suffix in (".md", ".tex", ".txt"):
            body = normalize(f.read_text(encoding="utf-8"))
            hits += [(str(f.relative_to(PACK)), k) for k in keys if k in body]
    files = sorted(str(p.relative_to(PACK)) for p in PACK.rglob("*") if p.is_file())
    res = {"files": files, "n_files": len(files), "paper_facts_lines": fx.count("\n"), "real_messages_checked": len(keys),
           "leak_hits": len(hits)}
    save_result(run, res, "paper_pack.json")
    if hits:
        print("LEAK HITS (file, first chars withheld):", [h[0] for h in hits]); raise SystemExit(1)
    print(json.dumps({k: v for k, v in res.items() if k != "files"}), "\n", "\n".join(files)); print(run["run_id"])


if __name__ == "__main__":
    main()
